# Trying Variables in python

student_name = "Rahul"
student_age = 24
course_fee = 15000.50
has_coding_experience = True

# Displaying the values of the variables
print("Name:", student_name)
print("Age:", student_age)
print("Course Fee:", course_fee)
print("Has Coding Experience:", has_coding_experience)

# Add 10 to age and display the new age
student_age += 10
print("New Age after adding 10:", student_age)

# Displaying the type of each variable
print("Type of student_name:", type(student_name))
print("Type of student_age:", type(student_age))
print("Type of course_fee:", type(course_fee))
print("Type of has_coding_experience:", type(has_coding_experience))

# changing the type of student_name to an Integer
student_name = 12345
print("New Student Name (as Integer):", student_name)