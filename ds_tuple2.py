# create a demo program to create examples of tuple assignment, index based access, and iteration using indexes

# Tuple assignment
my_tuple = (1, 2, 3, 4, 5)

# Index based access
print(my_tuple[0])  # Access first element
print(my_tuple[-1])  # Access last element

# Iteration using indexes
for i in my_tuple:
    print(i)  # Print each element in the tuple
    
    